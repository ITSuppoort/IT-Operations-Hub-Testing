import app from "./app";


// =====================================================
// SERVER PORT
// =====================================================

const PORT = Number(process.env.PORT) || 3001;


// =====================================================
// START SERVER
// =====================================================

app.listen(
    PORT,
    "0.0.0.0",
    () => {

        console.log(
            `API running on port ${PORT}`
        );

    }
);